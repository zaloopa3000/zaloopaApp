import SwiftUI

/// Один шар на экране.
struct Ball: Identifiable {
    let id = UUID()
    /// Центр шара в координатах экрана.
    var position: CGPoint
    /// Скорость в точках в секунду.
    var velocity: CGVector = .zero
    /// Радиус шара.
    var radius: CGFloat
    /// Цвета градиента внутри шара (2–3 сочетающихся оттенка).
    var colors: [Color]
    /// Направление градиента — у каждого шара своё, чтобы они не выглядели одинаково.
    var gradientAngle: Angle
    /// Яркость вспышки при ударе (0...1), затухает со временем.
    var flash: Double = 0
    /// Насколько шар сплющен после удара (0 — круглый). Только визуальный эффект, физика считает шар кругом.
    var squash: CGFloat = 0
    /// Направление от центра шара к точке последнего удара (радианы). Шар сжимается вдоль него,
    /// а сторона контакта остаётся на месте — у стены или у соседа.
    var squashAngle: CGFloat = 0

    /// «Вес» шара для столкновений: пропорционален площади, поэтому большие шары расталкивают маленькие.
    var mass: CGFloat { radius * radius }
}
